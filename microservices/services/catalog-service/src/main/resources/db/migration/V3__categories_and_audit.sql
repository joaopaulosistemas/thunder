-- Categorias (1 categoria : N produtos) e colunas de controle das entidades editaveis.
CREATE TABLE categories (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(120) NOT NULL UNIQUE,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version    BIGINT       NOT NULL DEFAULT 0
);

INSERT INTO categories (name) VALUES ('Livros'), ('Periféricos');

ALTER TABLE products
    ADD COLUMN category_id BIGINT REFERENCES categories (id),
    ADD COLUMN deleted     BOOLEAN     NOT NULL DEFAULT FALSE,
    ADD COLUMN created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    ADD COLUMN updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    ADD COLUMN version     BIGINT      NOT NULL DEFAULT 0;

UPDATE products SET category_id = (SELECT id FROM categories WHERE name = 'Livros')      WHERE sku LIKE 'BK-%';
UPDATE products SET category_id = (SELECT id FROM categories WHERE name = 'Periféricos') WHERE sku LIKE 'KB-%';

CREATE INDEX idx_products_category ON products (category_id);
