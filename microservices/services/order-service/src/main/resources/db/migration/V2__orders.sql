-- Copia local dos produtos (preco), alimentada por catalog.product-changed.
-- O order-service nunca consulta o catalogo de forma sincrona: se o catalogo cair, pedidos continuam entrando.
CREATE TABLE product_snapshot (
    product_id  BIGINT       PRIMARY KEY,
    name        VARCHAR(255) NOT NULL,
    price_cents INTEGER      NOT NULL
);

CREATE TABLE orders (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer    VARCHAR(120) NOT NULL,
    product_id  BIGINT       NOT NULL,
    quantity    INTEGER      NOT NULL CHECK (quantity > 0),
    total_cents BIGINT       NOT NULL,
    status      VARCHAR(20)  NOT NULL,
    created_at  TIMESTAMPTZ  NOT NULL
);
CREATE INDEX idx_orders_customer ON orders (customer, id DESC);
